#!/usr/bin/env node
/**
 * Regenerates docs/rules/00-index.md from the rules files themselves.
 *
 * The index is every rule's own opening sentence, with the file it lives in.
 * It is generated rather than written because a hand-kept index of 130 rules
 * is one that disagrees with the rules within a week -- the same reason the
 * User Access matrix is derived and not a second list of permissions.
 *
 * Run it after adding or renaming a rule. `npm run lint` does not, because a
 * stale index costs a grep rather than a wrong answer.
 */
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

const DIR = "docs/rules";
const files = readdirSync(DIR)
  .filter((f) => f.endsWith(".md") && f !== "00-index.md")
  .sort();

const sections = [];
let total = 0;

for (const file of files) {
  const text = readFileSync(join(DIR, file), "utf8");
  const title = text.match(/^# (.+)$/m)?.[1] ?? file;
  const rules = [];

  // A rule opens with "- **" at the start of a line; its first sentence runs
  // to the closing "**". Nested bullets (two spaces in) are part of a rule,
  // not rules of their own.
  const re = /^- \*\*(.+?)\*\*/gms;
  for (const m of text.matchAll(re)) {
    rules.push(m[1].replace(/\s+/g, " ").trim().replace(/[.,:;]$/, ""));
  }
  total += rules.length;
  sections.push({ file, title, rules });
}

const out = `# Every rule, by its own sentence

Generated by \`node scripts/build-rules-index.mjs\` -- do not hand-edit.

${total} rules across ${files.length} files. This exists so \`grep\` finds the
right file from a symptom: you rarely know a rule is called "a check that
could not be run is not a check that came back negative", but you do know you
are looking at a 403 that should have been a 503.

\`\`\`
rg -i "<the thing you are seeing>" docs/rules/
\`\`\`

${sections
  .map(
    (s) =>
      `## ${s.title}\n\n\`${DIR}/${s.file}\` -- ${s.rules.length} rules\n\n` +
      s.rules.map((r) => `- ${r}`).join("\n")
  )
  .join("\n\n")}
`;

writeFileSync(join(DIR, "00-index.md"), out);
console.log(`docs/rules/00-index.md: ${total} rules across ${files.length} files`);
